"""`margi ai-report`: a factual appendix on how margi was used in this thesis (no AI).

Built only from the records in margi/feedback/ and git. It lists every run and what it produced,
says how the separation between the student's text and margi's output is enforced, and checks the
whole history with the guard. It never drafts the student's declaration or AI statement.
"""

from __future__ import annotations

import html
from collections import Counter

from .config import MARGI_DIR, Config

MD = f"{MARGI_DIR}/ai-use.md"
HTML = f"{MARGI_DIR}/dash/ai-use.html"

WHAT = {
    "propose": lambda r: "project documentation from the student's proposal",
    "challenge": lambda r: f"{len((r.get('payload') or {}).get('challenges', []))} challenge questions; refinements the student confirmed",
    "outline": lambda r: "a length count per section (no AI)",
    "read": lambda r: f"relevance ratings for {len((r.get('payload') or {}).get('ratings', []))} PDFs",
    "todos": lambda r: "todo proposals reviewed by the student",
    "respond": lambda r: "the student's own answers to comments " + ", ".join(
        x.get("ref", "") for x in (r.get("payload") or {}).get("responses", [])),
    "submit-check": lambda r: "a submission check: quotations, bibliography, open items (no AI)",
    "defend": lambda r: f"{len((r.get('payload') or {}).get('questions', []))} mock-defense questions",
}


def _what(r: dict) -> str:
    cmd = r.get("command")
    if cmd == "grade":
        if (r.get("readiness") or {}).get("decision") == "not_ready":
            return "readiness check: not ready to grade"
        return f"rubric scores in {len(r.get('scores') or {})} categories and {len(r.get('comments') or [])} comments"
    return WHAT.get(cmd, lambda r: cmd or "")(r)


def build(cfg: Config) -> dict:
    from .guard import check_range
    from .save import counts
    from .lifecycle import load_records

    records = load_records(cfg)
    rows = [{"date": (r["provenance"].get("timestamp") or "")[:10], "command": r.get("command"), "scope": r.get("scope"),
             "model": r["provenance"].get("model") or ("student" if r.get("command") == "respond" else "none (deterministic)"
                                                     if r["provenance"].get("model_source") == "none" else "not reported"),
             "what": _what(r), "file": r["_file"]} for r in records]
    violations = None
    if cfg.has_git:
        try:
            violations = check_range(cfg.root, cfg, "HEAD")
        except Exception as e:  # noqa: BLE001 - an unreadable history is reported, not hidden
            violations = {"history": [f"could not check the history: {e}"]}
    return {
        "title": None,
        "rows": rows,
        "period": (rows[0]["date"], rows[-1]["date"]) if rows else None,
        "counts": Counter(r["command"] for r in rows),
        "models": sorted({r["model"] for r in rows if r["model"] not in ("student",) and not r["model"].startswith("none")}),
        "has_git": cfg.has_git,
        "violations": violations,
        "saves": counts(cfg),
    }


def _verdict(rep: dict) -> str:
    if not rep["has_git"]:
        return ("This project is not a git repository, so the separation could not be verified. "
                "The records below were still written by margi's scripts.")
    if rep["violations"]:
        n = len(rep["violations"])
        return (f"**The guard found {n} commit{'s' if n != 1 else ''} that break the separation** "
                "(listed at the end). The statement that margi wrote no text outside `margi/` can't be made for this history.")
    text = ("The guard checked every commit in this repository's history: margi wrote nothing outside `margi/`, "
            "and no commit mixes the student's files with margi's.")
    via, total = rep.get("saves") or (0, 0)
    if via:
        text += (f" {via} of {total} versions of the thesis were saved through margi, each approved by the student "
                 "in Claude Code's permission prompt" + ("; the student committed the others directly." if via < total else "."))
    return text


def markdown(cfg: Config, rep: dict) -> str:
    from .dashboard import _title

    lines = [f"# AI use: {_title(cfg)}", "",
             ("This appendix was generated by margi from its own records (`margi/feedback/`) and git. It is factual: "
              "it lists what the AI feedback tool did and how its output was kept apart from the thesis. "
              "The declaration of independence and any statement on AI use are written by the student."), ""]
    if not rep["rows"]:
        lines += ["margi has no records for this thesis yet.", "", "## Separation", "", _verdict(rep), ""]
        lines += _guard_findings(rep)
        return "\n".join(lines) + "\n"
    a, b = rep["period"]
    lines += ["## Summary", "",
              f"- Period: {a} to {b}, {len(rep['rows'])} recorded runs.",
              "- Runs per command: " + ", ".join(f"{k} {v}" for k, v in sorted(rep["counts"].items())) + ".",
              "- Models: " + (", ".join(rep["models"]) or "none reported") + ".",
              ("- margi gives feedback only: documentation of the plan, rubric scores, comments that name problems, "
               "literature ratings and todos. It never writes or rewrites thesis text."), "",
              "## Separation", "",
              _verdict(rep), "",
              ("How it is enforced: every AI run ends in `margi finalize`, which refuses to run if anything outside "
              "`margi/` changed and commits only `margi/`, as the margi bot. "
              + ("A commit hook and a CI check (`margi guard`) reject" if (cfg.root / ".github/workflows/margi-guard.yml").exists()
                 else "A commit hook (`margi guard`) rejects") + " commits that mix the two. margi saves the student's own files only after the "
              "student approves each save, under the student's name and never as the bot. To verify: "
              "`git log -- margi/` lists every AI contribution; `git log -- . ':(exclude)margi'` lists the "
              "student's own."), "",
              "## Every run", "",
              "| Date | Command | Scope | Model | What it produced | Record |",
              "|---|---|---|---|---|---|"]
    for r in rep["rows"]:
        lines.append(f"| {r['date']} | {r['command']} | {r['scope']} | {r['model']} | {r['what']} | `{r['file']}` |")
    lines += [""] + _guard_findings(rep)
    return "\n".join(lines).rstrip() + "\n"


def _guard_findings(rep: dict) -> list[str]:
    if not rep["violations"]:
        return []
    out = ["## Guard findings", ""]
    for sha, problems in rep["violations"].items():
        out += [f"- `{sha[:10]}`: {p}" for p in problems]
    return out


def to_html(md: str) -> str:
    """A small, printable rendering of the appendix (tables, headings, lists, code)."""
    out, table = [], False
    inline = lambda t: _inline(html.escape(t))
    for line in md.splitlines():
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                continue
            if not table:
                out.append("<table>")
                out.append("<tr>" + "".join(f"<th>{inline(c)}</th>" for c in cells) + "</tr>")
                table = True
                continue
            out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cells) + "</tr>")
            continue
        if table:
            out.append("</table>")
            table = False
        if line.startswith("# "):
            out.append(f"<h1>{inline(line[2:])}</h1>")
        elif line.startswith("## "):
            out.append(f"<h2>{inline(line[3:])}</h2>")
        elif line.startswith("- "):
            out.append(f"<p class='li'>{inline(line[2:])}</p>")
        elif line.strip():
            out.append(f"<p>{inline(line)}</p>")
    if table:
        out.append("</table>")
    style = ("body{font:16px/1.5 'Libertinus Serif',Georgia,serif;color:#1c1a18;background:#fff;max-width:960px;margin:40px auto;padding:0 24px}"
             "h1{font-size:26px;font-weight:600}h2{font-size:13px;font-family:'Gill Sans',system-ui,sans-serif;letter-spacing:.09em;"
             "text-transform:uppercase;border-bottom:1px solid #1c1a18;padding-bottom:6px;margin-top:32px}"
             "table{border-collapse:collapse;width:100%;font-size:14px}th,td{text-align:left;padding:6px 8px;border-bottom:1px solid #e3dfd8;"
             "vertical-align:top}th{border-bottom:1px solid #1c1a18;font-weight:400;font-family:system-ui,sans-serif;font-size:12px;"
             "text-transform:uppercase;letter-spacing:.08em;color:#6a645d}code{font:13px ui-monospace,Menlo,monospace}.li::before{content:'– '}")
    return f"<!doctype html><html lang='en'><head><meta charset='utf-8'><title>AI use</title><style>{style}</style></head><body>{''.join(out)}</body></html>\n"


def _inline(t: str) -> str:
    import re

    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    return re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)


def write(cfg: Config) -> tuple[str, dict]:
    rep = build(cfg)
    md = markdown(cfg, rep)
    (cfg.root / MD).write_text(md, encoding="utf-8")
    page = cfg.root / HTML
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(to_html(md), encoding="utf-8")
    return md, rep
